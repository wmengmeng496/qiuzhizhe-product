from pathlib import Path
from docx import Document
from docx.oxml.ns import qn

SOURCE = Path('/Users/wuqiong/Desktop/职引简历AI求职工作台系统_操作说明书_V1.1_人话版.docx')
OUTPUT = Path('/Users/wuqiong/Desktop/文件夹们/我自己的/求职者产品/职引简历AI求职工作台系统_操作说明书_V1.1_人话版_统一字体.docx')
FONT = 'Microsoft YaHei'
EAST_ASIA_FONT = '微软雅黑'


def apply_rfonts(rpr):
    if rpr is None:
        return
    rfonts = rpr.get_or_add_rFonts()
    rfonts.set(qn('w:ascii'), FONT)
    rfonts.set(qn('w:hAnsi'), FONT)
    rfonts.set(qn('w:eastAsia'), EAST_ASIA_FONT)
    rfonts.set(qn('w:cs'), FONT)


def apply_run(run):
    run.font.name = FONT
    apply_rfonts(run._element.get_or_add_rPr())


def iter_paragraphs(container):
    for paragraph in container.paragraphs:
        yield paragraph
    for table in container.tables:
        for row in table.rows:
            for cell in row.cells:
                yield from iter_paragraphs(cell)


doc = Document(SOURCE)

# Styles control any text without direct run formatting.
for style in doc.styles:
    if not hasattr(style, 'font'):
        continue
    style.font.name = FONT
    apply_rfonts(style._element.get_or_add_rPr())

# Body text and all nested table text.
for paragraph in iter_paragraphs(doc):
    for run in paragraph.runs:
        apply_run(run)

# Headers and footers are separate document parts.
for section in doc.sections:
    for part in (section.header, section.footer, section.first_page_header,
                 section.first_page_footer, section.even_page_header,
                 section.even_page_footer):
        for paragraph in iter_paragraphs(part):
            for run in paragraph.runs:
                apply_run(run)

# Theme defaults can otherwise override runs generated by Word later.
styles_root = doc.styles.element
doc_defaults = styles_root.find(qn('w:docDefaults'))
if doc_defaults is not None:
    rpr_default = doc_defaults.find(qn('w:rPrDefault'))
    if rpr_default is not None:
        rpr = rpr_default.find(qn('w:rPr'))
        if rpr is not None:
            apply_rfonts(rpr)

doc.save(OUTPUT)
print(OUTPUT)
